import numpy as np
import pandas as pd
from scipy import stats

SEED = 42
N_SCENARIO = 10

# ==================== Severity functions ====================

def severity_percentile() :
    """
    returns a severity score based on on predefined discrete probability bins
    default values come from the Adjusted Damage fitted distribution
    """
    severity_bins = [1, 2, 3, 4]
    severity_probs = [0.50, 0.30, 0.10, 0.10]
    return int(np.random.choice(severity_bins, p = severity_probs))

def severity_proxy(s=2.3054, mu=11.988, loc = 0.0) :
    """
    returns a continuous severity proxy drawn from a lognormal distribution
    """
    return float(stats.lognorm.rvs(s = s, loc = loc, scale = np.exp(mu)))

severity_functions = {
    "severity_percentile" : severity_percentile,
    "severity_proxy" : severity_proxy
}

def generate_mc_scenario_only(
    nb_n_monthly,
    nb_p,
    country_weights,
    duration_pools,
    num_scenarios=N_SCENARIO,
    n_years = 1,
    severity_function = "severity_percentile",
    seed = SEED
):
    """
    Generate Monte Carlo disaster scenarios and applies attenuation 
    Note: We draw event duration from pool of existing historical durations, but this was not used later on
    
    1. Aggregate european event count via negative binomial
    2. Multinomial spatial allocation to countries
    3. Duration and severity draw

    Args:
        nb_n_monthly, nb_p: parameters for negative binomial distribution
        country_weights: dictionary of historical relative frequencies per country
        duration_pools: 
        num_scenarios: number of scenarios to generate
        n_years: number of years to simulate per scenario
        severity_function: string for choose the severity function, by default continuous, drawn from fitted distribution 
    
    Returns a DataFrame with all disruptions events
    """
    np.random.seed(seed)

    # 1.
    countries = list(country_weights.keys())
    proba_vector = np.array([country_weights[c] for c in countries], dtype=float)
    proba_vector = proba_vector / proba_vector.sum()

    scenarios = [f"s_{i}" for i in range(1, num_scenarios + 1)]
    event_records = []
    event_counter = 0

    for s in scenarios:
        for year in range(1, n_years + 1) :
            for month in range(1, 13):
                month_events = np.random.negative_binomial(n=nb_n_monthly, p=nb_p)

                if month_events == 0:
                    continue

                allocations = np.random.multinomial(n=month_events, pvals=proba_vector)
                events_by_country = dict(zip(countries, allocations))

                for country, count in events_by_country.items():
                    for _ in range(count):
                        event_counter += 1
                        event_id = f"evt_{event_counter}"

                        durations = duration_pools.get(
                            country, duration_pools.get("Fallback", [1])
                        )
                        duration_days = int(np.random.choice(durations))

                        severity = severity_functions[severity_function]()

                        event_records.append({
                            "scenario_id": s,
                            "year" : year,
                            "month": month,
                            "event_id": event_id,
                            "country": country,
                            "duration_days": duration_days,
                            "severity": severity,
                        })

    return pd.DataFrame(event_records)


def is_warehouse_hit(candidate_warehouses, event_scenarios, default_alpha = 0.25):
    """
    Take the generated disaster scenarios events and applies facility attenuation logic

    Args:
        candidate_warehouses: dictionary of warehouses mapping facilities to {country: str, alpha: float}
        event_scenarios: dataframe generated by generate_mc_scenario_only
        default_alpha: default attenuation probability if alpha is missing (arbitrary default value)
    
    Returns a dataframe detailing which facilities were hit by which event
    """

    columns = [
            "scenario_id", "year", "month", "event_id", "country",
            "warehouse", "is_hit", "duration_days", "severity"
        ]
    
    if event_scenarios.empty :
        return pd.DataFrame(columns = columns)
    event_records = []

    for _, row in event_scenarios.iterrows() :

        country = str(row["country"]).strip()

        for warehouse, config in candidate_warehouses.items():
            warehouse_country = str(config["country"]).strip()

            if warehouse_country.lower() == country.lower() :
                # attenuation hit test like in chapter 10
                alpha = config.get("alpha", default_alpha)
                is_hit = bool(np.random.rand() < alpha)
        
                event_records.append({
                    "scenario_id": row["scenario_id"],
                    "year" : row.get("year", 1),
                    "month": row["month"],
                    "event_id": row["event_id"],
                    "country": row["country"],
                    "warehouse": warehouse,
                    "is_hit": is_hit,
                    "duration_days": row["duration_days"],
                    "severity": row["severity"],
                })

    if not event_records :
        return pd.DataFrame(columns = columns)

    return pd.DataFrame(event_records)